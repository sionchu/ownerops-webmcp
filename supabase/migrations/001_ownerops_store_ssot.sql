-- Current market reference: latest, highest-confidence observation for each key.
create or replace view public.oo_latest_reference_prices as
select distinct on (market_id, reference_key)
  id,
  raw_observation_id,
  source_id,
  ingredient_id,
  reference_key,
  market_id,
  geography,
  price_level,
  original_label,
  original_price,
  original_currency,
  original_quantity,
  original_unit,
  price_per_base_unit,
  base_unit,
  confidence,
  observed_at,
  fetched_at,
  source_url,
  metadata
from public.oo_normalized_price_observations
order by market_id, reference_key, observed_at desc, confidence desc, fetched_at desc;

-- Latest store purchase actual, normalized to invoice unit and usable yield.
create or replace view public.oo_latest_store_purchase_costs as
select distinct on (r.store_id, r.item_id)
  r.store_id,
  r.item_id,
  r.ingredient_id,
  r.received_at,
  r.currency_code,
  r.quantity,
  r.unit,
  r.total_cost,
  r.purchase_form,
  coalesce(r.yield_rate, i.store_yield_rate, 1.0) as yield_rate,
  case when r.quantity > 0 then r.total_cost / r.quantity else null end as actual_unit_cost,
  case
    when r.quantity > 0 and coalesce(r.yield_rate, i.store_yield_rate, 1.0) > 0
      then (r.total_cost / r.quantity) / coalesce(r.yield_rate, i.store_yield_rate, 1.0)
    else null
  end as effective_unit_cost
from public.oo_purchase_receipts r
join public.oo_inventory_items i on i.store_id = r.store_id and i.item_id = r.item_id
order by r.store_id, r.item_id, r.received_at desc;

