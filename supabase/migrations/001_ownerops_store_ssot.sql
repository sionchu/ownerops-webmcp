-- OwnerOps Store SSOT / Reference Cache
-- Target: PostgreSQL / Supabase
-- Principle: store actuals are truth; public market data is reference evidence only.

create extension if not exists pgcrypto;

create or replace function public.oo_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

